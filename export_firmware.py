"""Export a trained LeakSNN + test recordings to C headers for the ESP32-S3 / Wokwi firmware.

  firmware/wokwi_esp32s3/snn_weights.h   weights, decay factors, thresholds, alarm threshold
  firmware/wokwi_esp32s3/test_streams.h  encoder spike streams of test clips + PyTorch reference logits

Default model: runs/seeds/0/snn.pt with its FA-5 % threshold from runs/thresholds.json;
falls back to runs/snn.pt (first training run) with threshold P = 0.9 if those do not exist yet.
Check the C++ port afterwards:  c++ -O2 -std=c++17 firmware/host_test/host_test.cpp -o host_test && ./host_test
"""
import argparse, json, os
import numpy as np
import pandas as pd
import torch
from gasleak.models import LeakSNN
from gasleak import metrics as M

OUT = "firmware/wokwi_esp32s3"
# (name, selector on test metadata); the first test clip matching each selector is exported
CLIPS = [("no leak, quiet room", lambda m: (m.label == 0) & (m.scene == "quiet")),
         ("no leak, factory noise", lambda m: (m.label == 0) & (m.scene == "factory")),
         ("leak, SNR 20 dB", lambda m: (m.label == 1) & (m.snr_db == 20)),
         ("leak, SNR 0 dB", lambda m: (m.label == 1) & (m.snr_db == 0)),
         ("leak, SNR -5 dB", lambda m: (m.label == 1) & (m.snr_db == -5)),
         ("leak, SNR -10 dB", lambda m: (m.label == 1) & (m.snr_db == -10))]


def c_float(v):
    s = f"{float(v):.9g}"
    return (s if any(c in s for c in ".en") else s + ".0") + "f"


def c_array(name, a, ctype="float", per_line=8):
    """1-D or 2-D numpy array -> C initializer (rows of 2-D arrays in their own braces)."""
    a = np.asarray(a)
    fmt = c_float if ctype == "float" else str

    def row(r):
        flat = [fmt(v) for v in r]
        return ",\n  ".join(", ".join(flat[i:i + per_line]) for i in range(0, len(flat), per_line))
    body = row(a) if a.ndim == 1 else ",\n  ".join("{" + row(r) + "}" for r in a)
    dims = "".join(f"[{d}]" for d in a.shape)
    return f"static const {ctype} {name}{dims} = {{\n  {body}\n}};\n"


def default_model():
    if os.path.exists("runs/seeds/0/snn.pt") and os.path.exists("runs/thresholds.json"):
        return "runs/seeds/0/snn.pt", json.load(open("runs/thresholds.json"))["0"]["snn"]["0.05"], "seed 0, FA 5 %"
    return "runs/snn.pt", float(np.log(0.9 / 0.1)), "first training run, P(leak) > 0.9"


if __name__ == "__main__":
    ckpt, tau, note = default_model()
    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default=ckpt)
    ap.add_argument("--tau", type=float, default=tau, help="alarm threshold (logit)")
    a = ap.parse_args()
    if a.ckpt != ckpt or a.tau != tau:
        note = "custom"
    model = LeakSNN(); model.load_state_dict(torch.load(a.ckpt)); model.eval()
    lif = [model.lif1, model.lif2]
    assert all(l.reset_mechanism == "subtract" for l in lif), "C++ port implements reset by subtraction"
    beta = [float(l.beta.detach().clamp(0, 1)) for l in lif + [model.out]]
    thr = [float(l.threshold) for l in lif]
    sd = {k: v.detach().numpy() for k, v in model.state_dict().items()}

    with open(f"{OUT}/snn_weights.h", "w") as f:
        f.write(f"// generated by export_firmware.py from {a.ckpt} ({note}) - do not edit\n#pragma once\n")
        f.write(f'#define SNN_SOURCE "{os.path.basename(os.path.dirname(a.ckpt)) or "runs"}/{os.path.basename(a.ckpt)} ({note})"\n')
        f.write(f"#define SNN_N_IN {model.fc1.in_features}\n#define SNN_N_HID {model.fc1.out_features}\n")
        f.write(f"#define SNN_WARMUP {M.WARMUP}\n#define SNN_K {M.K}\n")
        f.write(f"static const float SNN_TAU = {c_float(a.tau)};      // alarm threshold (logit)\n")
        for name, v in [("SNN_BETA1", beta[0]), ("SNN_BETA2", beta[1]), ("SNN_BETA3", beta[2]),
                        ("SNN_THR1", thr[0]), ("SNN_THR2", thr[1]), ("SNN_B3", sd["fc3.bias"][0]),
                        ("SNN_BIAS_OUT", sd["bias_out"])]:
            f.write(f"static const float {name} = {c_float(v)};\n")
        # weights stored transposed: one contiguous row per presynaptic neuron (event-driven access)
        f.write(c_array("SNN_W1T", sd["fc1.weight"].T)); f.write(c_array("SNN_B1", sd["fc1.bias"]))
        f.write(c_array("SNN_W2T", sd["fc2.weight"].T)); f.write(c_array("SNN_B2", sd["fc2.bias"]))
        f.write(c_array("SNN_W3", sd["fc3.weight"][0]))

    d = np.load("data/synth/dataset.npz")
    meta = pd.read_csv("data/synth/meta.csv")
    ev = d["events"]
    te = np.where(meta.split == "test")[0]
    mte = meta.iloc[te].reset_index(drop=True)
    T = ev.shape[1]
    with open(f"{OUT}/test_streams.h", "w") as f:
        f.write(f"// generated by export_firmware.py: test clips of data/synth, reference logits from {a.ckpt}\n#pragma once\n")
        f.write(f"#include <stdint.h>\n#define STREAM_T {T}\n#define N_STREAMS {len(CLIPS)}\n")
        f.write("struct SpikeStream { const char* name; int label; int onset_ms; int py_alarm_ms;\n"
                "                const uint16_t* ev; uint32_t n_ev; const float* ref_logit; };\n")
        entries = []
        for k, (name, pick) in enumerate(CLIPS):
            i = te[np.where(pick(mte))[0][0]]
            e = ev[i].astype(np.float32)
            with torch.no_grad():
                z = model(torch.from_numpy(e[None]))[0][0].numpy()
            tt, ch = np.nonzero(ev[i])                    # sorted by time, then channel
            alarm = int(M.first_alarm(M.window_min(z[None]), a.tau, np.array([M.WARMUP]), np.array([T]))[0])
            onset = int(round(meta.onset_s[i] * 1000)) if meta.label[i] == 1 else -1
            f.write(f"// clip {i}: {name}\n")
            f.write(c_array(f"EV{k}", (tt << 5) | ch, "uint16_t", 16))
            f.write(c_array(f"REF{k}", z))
            entries.append(f'  {{"{name}", {int(meta.label[i])}, {onset}, {alarm}, EV{k}, {len(tt)}, REF{k}}}')
            print(f"{name:24s} clip {i:4d}  events {len(tt):5d}  onset {onset:4d} ms  PyTorch alarm {alarm:4d} ms")
        f.write("static const SpikeStream STREAMS[N_STREAMS] = {\n" + ",\n".join(entries) + "\n};\n")
    print(f"wrote {OUT}/snn_weights.h and {OUT}/test_streams.h  ({a.ckpt}, tau = {a.tau:.3f}, {note})")
